/** Pull the outermost {...} out of a model reply (handles code fences and chatter). */
export function extractJson(raw: string): unknown {
  const s = raw.replace(/```(?:json)?/gi, '').trim()
  const a = s.indexOf('{')
  const b = s.lastIndexOf('}')
  if (a < 0 || b <= a) throw new Error('No JSON object in reply')
  const body = s.slice(a, b + 1)
  try {
    return JSON.parse(body)
  } catch {
    // Common slips: trailing commas, smart quotes around keys.
    return JSON.parse(body.replace(/,\s*([}\]])/g, '$1').replace(/[“”]/g, '"'))
  }
}

const str = (v: unknown): string => (typeof v === 'string' ? v.trim() : typeof v === 'number' ? String(v) : '')
const strList = (v: unknown, max: number): string[] =>
  Array.isArray(v) ? v.map((x) => (typeof x === 'object' && x && 'text' in x ? str((x as { text: unknown }).text) : str(x))).filter(Boolean).slice(0, max) : []

function toSeconds(v: unknown): number {
  if (typeof v === 'number' && Number.isFinite(v)) return Math.max(0, v)
  const s = str(v).replace(/[[\]]/g, '')
  const m = /^(\d{1,2}):(\d{2})/.exec(s)
  if (m) return Number(m[1]) * 60 + Number(m[2])
  const n = Number.parseFloat(s)
  return Number.isFinite(n) ? Math.max(0, n) : 0
}

/** Validate/coerce a parsed object into a SessionSummary (+ title). Throws if it's unusable. */
export function coerceSummary(obj: unknown, model: string, durationS: number): SummaryDraft {
  if (!obj || typeof obj !== 'object') throw new Error('Summary is not an object')
  const o = obj as Record<string, unknown>
  const tldr = str(o.tldr ?? o.TLDR ?? o.summary)
  if (!tldr) throw new Error('Summary is missing tldr')
  const timeline: TimelineItem[] = Array.isArray(o.timeline)
    ? (o.timeline as unknown[])
        .map((x) => {
          const it = (x ?? {}) as Record<string, unknown>
          const kind: TimelineItem['kind'] = str(it.kind).toLowerCase().startsWith('screen') ? 'screen' : 'speech'
          return { t: Math.min(toSeconds(it.t ?? it.time), Math.max(durationS, 1)), kind, text: str(it.text ?? it.description) }
        })
        .filter((x) => x.text)
        .sort((a, b) => a.t - b.t)
        .slice(0, 24)
    : []
  const actionItems = Array.isArray(o.actionItems ?? o.action_items)
    ? strList(o.actionItems ?? o.action_items, 10).map((text) => ({ text, done: false }))
    : []
  const summary: SessionSummary = {
    tldr,
    keyPoints: strList(o.keyPoints ?? o.key_points, 10),
    timeline,
    topics: strList(o.topics, 10).map((t) => t.replace(/^#/, '')),
    actionItems,
    generatedAt: nowIso(),
    model
  }
  const title = str(o.title).replace(/^["']|["']$/g, '').slice(0, 60)
  return { title, summary }
}

/** Generates a summary (Claude when available, else mock). Never throws. */
export async function generateSummary(detail: SessionDetail, userName: string): Promise<SummaryDraft> {
  // Respect per-session privacy: Claude access off → summarize on-device only.
  const client = detail.access?.ai === false ? null : getAnthropic()
  const empty = !detail.segments.length && !detail.events.length
  if (client && !empty) {
    try {
      const ctx = buildContext(detail)
      const msg = await client.messages.create({
        model: MODELS.smart,
        max_tokens: 1800,
        system: SUMMARY_SYSTEM,
        messages: [{ role: 'user', content: summaryUserPrompt(ctx.text, userName) }]
      })
      return coerceSummary(extractJson(textOf(msg)), MODELS.smart, detail.durationS)
    } catch (e) {
      log.error('Claude summary failed — using mock summary', e)
    }
  }
  return mockSummary(detail)
}

export const isDefaultTitle = (t: string): boolean => !t.trim() || /^session\s*[·•-]/i.test(t.trim()) || /^untitled session$/i.test(t.trim())

/** Persist summary JSON and rename default-titled sessions. Returns the (possibly new) title. */
export function storeSummary(detail: SessionDetail, draft: SummaryDraft): string {
  // Rename when the title is still a default, or was itself generated by a previous summary (never overwrite a user's rename).
  const prevGenerated = (detail.summary as (SessionSummary & { title?: string }) | null)?.title
  const autoTitled = isDefaultTitle(detail.title) || (!!prevGenerated && prevGenerated === detail.title)
  const title = autoTitled && draft.title ? draft.title : detail.title
  run('UPDATE sessions SET summary_json = ?, title = ? WHERE id = ?', [JSON.stringify({ ...draft.summary, title: draft.title || undefined }), title, detail.id])
  return title
}
